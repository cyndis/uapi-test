#![allow(non_camel_case_types)]

use bytemuck::{Pod, Zeroable};

// DRM command offsets
const DRM_COMMAND_BASE: u32 = 0x40;
const TEGRA_GEM_CREATE: u32 = 0x00;
const TEGRA_GEM_MMAP: u32 = 0x01;
const TEGRA_SYNCPT_INCR: u32 = 0x03;
const TEGRA_CHANNEL_OPEN: u32 = 0x10;
const TEGRA_CHANNEL_CLOSE: u32 = 0x11;
const TEGRA_CHANNEL_MAP: u32 = 0x12;
const TEGRA_CHANNEL_UNMAP: u32 = 0x13;
const TEGRA_CHANNEL_SUBMIT: u32 = 0x14;
const TEGRA_SYNCPOINT_ALLOCATE: u32 = 0x20;
const TEGRA_SYNCPOINT_FREE: u32 = 0x21;
const TEGRA_SYNCPOINT_WAIT: u32 = 0x22;
const DRM_GEM_CLOSE: u32 = 0x09;
const DRM_PRIME_HANDLE_TO_FD: u32 = 0x2D;

// --- ioctl functions (generated by nix macros) ---

nix::ioctl_readwrite!(ioctl_gem_create, b'd', DRM_COMMAND_BASE + TEGRA_GEM_CREATE, drm_tegra_gem_create);
nix::ioctl_readwrite!(ioctl_gem_mmap, b'd', DRM_COMMAND_BASE + TEGRA_GEM_MMAP, drm_tegra_gem_mmap);
nix::ioctl_readwrite!(ioctl_syncpt_incr, b'd', DRM_COMMAND_BASE + TEGRA_SYNCPT_INCR, drm_tegra_syncpt_incr);
nix::ioctl_readwrite!(ioctl_channel_open, b'd', DRM_COMMAND_BASE + TEGRA_CHANNEL_OPEN, drm_tegra_channel_open);
nix::ioctl_readwrite!(ioctl_channel_close, b'd', DRM_COMMAND_BASE + TEGRA_CHANNEL_CLOSE, drm_tegra_channel_close);
nix::ioctl_readwrite!(ioctl_channel_map, b'd', DRM_COMMAND_BASE + TEGRA_CHANNEL_MAP, drm_tegra_channel_map);
nix::ioctl_readwrite!(ioctl_channel_unmap, b'd', DRM_COMMAND_BASE + TEGRA_CHANNEL_UNMAP, drm_tegra_channel_unmap);
nix::ioctl_readwrite!(ioctl_channel_submit, b'd', DRM_COMMAND_BASE + TEGRA_CHANNEL_SUBMIT, drm_tegra_channel_submit);
nix::ioctl_readwrite!(ioctl_syncpoint_allocate, b'd', DRM_COMMAND_BASE + TEGRA_SYNCPOINT_ALLOCATE, drm_tegra_syncpoint_allocate);
nix::ioctl_readwrite!(ioctl_syncpoint_free, b'd', DRM_COMMAND_BASE + TEGRA_SYNCPOINT_FREE, drm_tegra_syncpoint_free);
nix::ioctl_readwrite!(ioctl_syncpoint_wait, b'd', DRM_COMMAND_BASE + TEGRA_SYNCPOINT_WAIT, drm_tegra_syncpoint_wait);
nix::ioctl_write_ptr!(ioctl_gem_close, b'd', DRM_GEM_CLOSE, drm_gem_close);
nix::ioctl_readwrite!(ioctl_prime_handle_to_fd, b'd', DRM_PRIME_HANDLE_TO_FD, drm_prime_handle);

// --- Flags ---

pub const DRM_TEGRA_CHANNEL_MAP_READ: u32 = 1;
pub const DRM_TEGRA_CHANNEL_MAP_WRITE: u32 = 2;

pub const DRM_TEGRA_SUBMIT_CMD_GATHER_UPTR: u32 = 0;
pub const DRM_TEGRA_SUBMIT_CMD_WAIT_SYNCPT: u32 = 1;

